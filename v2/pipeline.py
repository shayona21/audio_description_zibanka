"""Parse -> pass 1 -> pass 1.5 -> pass 2 -> place -> tracks -> ZIP.

  pass 1     ElevenLabs generates every row; its leading silence is trimmed and the take is measured
             against its slot (``audio_speed.measure``).
  pass 1.5   rows whose desired speed is outside MIN_SPEED..MAX_SPEED are rewritten by Gemini and
             regenerated by ElevenLabs, up to MAX_REWRITE_ATTEMPTS times. Each attempt is told how
             the earlier ones came out; the attempt whose speed is closest to 1.0x is kept, and the
             loop stops early once a take is within the normal 2%. If no rewrite reaches the limits,
             the best rewrite is kept at 1.0x and the row is flagged MANUAL_REVIEW.
             Lines of SKIP_REWRITE_MAX_WORDS words or fewer (not counting [tags]) are never rewritten:
             rewriting a word or two loses its meaning in context. They keep their pass 1 take at 1.0x
             and are marked SKIPPED_REWRITE. Every other row keeps its pass 1 take.
             The rewritten takes are only an intermediate step; they are not in the download.
  pass 2     FFmpeg applies the desired speed (held within the limits) to every row that is not
             normal, flagged or skipped, then each line is measured again.

ZIP layout (names are lowercase, spaces as "_"):
  pass1/lines/ep<ep>_<character>_row<row>.wav     the ElevenLabs dub, leading silence trimmed
  pass1/tracks/ep<ep>_<character>.wav             one timeline per <character, episode>, from pass 1
  pass2/lines/ep<ep>_<character>_row<row>.wav     each line after pass 1.5 and pass 2 (the audio delivered)
  pass2/tracks/ep<ep>_<character>.wav             one timeline per <character, episode>, from pass 2
  ep<ep>_timeline.csv                             combined timeline per episode (pass 2, final dialogue)
  processing_report.csv                           one record per row, every pass side by side
  script.xlsx                                     copy of the input workbook

Both passes' tracks are placed with the same rule (``place_dialogue``): each line starts on its TCR
IN, or straight after the same character's previous line if that one runs late. Each pass is placed
with its own clip lengths, so a long pass 1 line can push later lines further than in pass 2. The
timelines and the report's adjusted TCRs describe pass 2, the audio delivered.
"""

from collections import defaultdict
from dataclasses import dataclass, replace
from pathlib import Path
import shutil
import tempfile

from .audio_builder import build_track, read_clip
from .audio_speed import (MAX_SPEED, MIN_SPEED, NORMAL_TOLERANCE_PERCENT, SUCCESS_TARGET_PERCENT, Measurement,
                          apply_pass2, check_ffmpeg, format_sig, measure, sig, success_rate, trim_leading_silence)
from .excel_parser import parse_excel
from .exporter import (LINES_DIR, PASS1_DIR, PASS2_DIR, SCRIPT_NAME, TRACKS_DIR, StreamingArchive, format_tcr,
                       line_name, track_names, timeline_names, write_report, write_timeline)
from .rewrite import Attempt, GeminiRewriter, RewriteError, RewriteRequest, word_count
from .timing import place_dialogue
from .tts_client import ElevenLabsClient

MAX_REWRITE_ATTEMPTS = 2
SKIP_REWRITE_MAX_WORDS = 2           # lines this short are never sent to Gemini
SKIPPED_NOTE = "skipped AI rewriting due to length"
KEPT_DIR = "kept"                    # work folder, not in the ZIP: the take pass 2 starts from
MANUAL_REVIEW_WARNING_PERCENT = 10   # more flagged rows than this points to a problem earlier in the pipeline


@dataclass
class Line:
    """Everything known about one row as it goes through the passes."""
    row: object
    trim_ms: int
    pass1: Measurement
    text: str = ""                 # the dialogue spoken in the delivered audio
    pass1_5: Measurement = None
    rewrite_calls: int = 0
    rewritten: bool = False
    manual_review: bool = False
    skipped: bool = False          # too short to rewrite: kept at 1.0x, SKIPPED_REWRITE
    note: str = ""
    pass2_speed: float = 1.0
    pass2: Measurement = None
    clip_ms: int = 0               # full pass 2 clip length, used for placement
    pass1_clip_ms: int = 0         # full pass 1 clip length, used to place the pass 1 tracks

    @property
    def slot_ms(self):
        return self.row.end_ms - self.row.start_ms


def run_pipeline(excel_path, output_path, *, fps=25, sheet_name=None, synthesize=None, rewrite=None,
                 progress=print, progress_state=None, fit_lines=True):
    """``fit_lines=False`` skips pass 1.5 and pass 2 (each clip keeps its pass 1 take); tests use it to
    check the placement rules on their own."""
    # All spreadsheet validation happens before constructing the API clients.
    rows = parse_excel(excel_path, fps=fps, sheet_name=sheet_name)
    output_path = Path(output_path)
    if output_path.suffix.lower() != ".zip":
        raise ValueError("Output must be a .zip file")
    if output_path.exists():
        raise ValueError(f"Output already exists: {output_path}; choose a new filename")
    check_ffmpeg()  # leading-silence trim and pass 2 both need it; checked before any ElevenLabs request
    synthesize = synthesize if synthesize is not None else ElevenLabsClient()
    if fit_lines and rewrite is None:
        rewrite = GeminiRewriter()   # a missing GEMINI_API_KEY fails here, before any ElevenLabs request
    output_path.parent.mkdir(parents=True, exist_ok=True)
    names = track_names({row.group for row in rows})

    def update_state(percent, phase):
        if progress_state is not None:
            progress_state({"percent": percent, "phase": phase})

    def generate(row, text):
        """One ElevenLabs take with its leading silence trimmed: ``(wav, ms trimmed)``."""
        try:
            take, trimmed = trim_leading_silence(synthesize(text, row.voice_id))
            read_clip(take)   # rejects empty audio
        except Exception as exc:
            raise RuntimeError(f"Excel row {row.row_number}: {exc}") from exc
        return take, trimmed

    progress(f"Validated {len(rows)} dialogue rows; {len(names)} tracks; {fps} fps")
    with tempfile.TemporaryDirectory(prefix="ad-v2-", dir=output_path.parent) as workspace:
        workspace = Path(workspace)
        for folder in (f"{PASS1_DIR}/{LINES_DIR}", f"{PASS1_DIR}/{TRACKS_DIR}", f"{KEPT_DIR}/{LINES_DIR}",
                       f"{PASS2_DIR}/{LINES_DIR}", f"{PASS2_DIR}/{TRACKS_DIR}"):
            (workspace / folder).mkdir(parents=True)

        def save(folder, row, wav):
            path = workspace / folder / LINES_DIR / line_name(row)
            path.write_bytes(wav)
            return path

        # ---- pass 1: generate, trim, measure ------------------------------------------------------
        update_state(0, "Pass 1: generating audio")
        lines = {}
        for index, row in enumerate(rows, start=1):
            progress(f"Pass 1 {index}/{len(rows)}: Excel row {row.row_number}, episode {row.episode}, {row.character}")
            take, trimmed = generate(row, row.text)
            line = Line(row, trimmed, measure(take, row.end_ms - row.start_ms), text=row.text)
            line.pass1_5 = line.pass1
            line.pass1_clip_ms = len(read_clip(take))
            save(PASS1_DIR, row, take)
            save(KEPT_DIR, row, take)
            lines[row.row_number] = line
            progress(f"Excel row {row.row_number}: trimmed {trimmed} ms; {describe(line.pass1)}")
            update_state(round(index / len(rows) * 60), "Pass 1: generating audio")

        # ---- pass 1.5: rewrite lines outside the speed limits -------------------------------------
        to_rewrite = [line for line in lines.values() if fit_lines and line.pass1.needs_rewrite]
        progress(f"Pass 1.5: {len(to_rewrite)} of {len(rows)} rows need {MIN_SPEED}x-{MAX_SPEED}x or beyond; "
                 "rewriting them with Gemini")
        for index, line in enumerate(to_rewrite, start=1):
            update_state(60 + round(index / len(to_rewrite) * 25), "Pass 1.5: rewriting long and short lines")
            rewrite_line(line, rows, rewrite, generate, save, progress)

        # ---- pass 2: FFmpeg speed -----------------------------------------------------------------
        update_state(85, "Pass 2: fitting lines to their slots")
        clip_paths = {}
        for line in lines.values():
            row = line.row
            take = (workspace / KEPT_DIR / LINES_DIR / line_name(row)).read_bytes()
            try:
                fitted, line.pass2_speed = (apply_pass2(take, line.pass1_5, line.manual_review or line.skipped)
                                            if fit_lines else (take, 1.0))
                line.clip_ms = len(read_clip(fitted))
            except Exception as exc:
                raise RuntimeError(f"Excel row {row.row_number}: {exc}") from exc
            line.pass2 = measure(fitted, line.slot_ms)
            clip_paths[row.row_number] = save(PASS2_DIR, row, fitted)
            if line.pass2_speed != 1.0:
                progress(f"Pass 2: Excel row {row.row_number} at {format_sig(line.pass2_speed)}x; {describe(line.pass2)}")

        # Placement, tracks and timelines use the dialogue actually spoken.
        final_rows = [replace(row, text=lines[row.row_number].text) for row in rows]
        progress("Resolving audio collisions independently for each episode and character")
        placements = {p.row.row_number: p for p in
                      place_dialogue(final_rows, {n: line.clip_ms for n, line in lines.items()})}
        pass1_placements = {p.row.row_number: p for p in
                            place_dialogue(rows, {n: line.pass1_clip_ms for n, line in lines.items()})}
        pass1_paths = {row.row_number: workspace / PASS1_DIR / LINES_DIR / line_name(row) for row in rows}
        # Disk use is kept low by streaming into the ZIP: each full-length track goes into the ZIP
        # the moment it is built and its WAV is deleted, so only one track is ever on disk.
        with StreamingArchive(output_path) as archive:
            for folder in (PASS1_DIR, PASS2_DIR):
                for path in sorted((workspace / folder / LINES_DIR).iterdir()):
                    archive.add(path, path.relative_to(workspace).as_posix())

            update_state(90, "Building character tracks")
            passes = ((PASS1_DIR, pass1_placements, pass1_paths), (PASS2_DIR, placements, clip_paths))
            for step, (pass_dir, pass_placements, paths) in enumerate(passes):
                groups, episode_ends = defaultdict(list), defaultdict(int)
                for placed in pass_placements.values():
                    row = placed.row
                    groups[row.group].append((placed, paths[row.row_number]))
                    episode_ends[row.episode] = max(episode_ends[row.episode], row.end_ms, placed.end_ms)
                for index, group in enumerate(sorted(groups), start=1):
                    progress(f"Building {pass_dir}/{TRACKS_DIR}/{names[group]}")
                    track_path = workspace / pass_dir / TRACKS_DIR / names[group]
                    build_track(groups[group], episode_ends[group[0]], track_path)
                    archive.add(track_path, track_path.relative_to(workspace).as_posix(), delete=True)
                    update_state(90 + round((step + index / len(groups)) / len(passes) * 9), "Building character tracks")

            update_state(99, "Packaging download")
            records = [report_record(lines[row.row_number], placements[row.row_number], names[row.group], fps)
                       for row in rows]
            episode_timelines = defaultdict(list)
            for placed in placements.values():
                episode_timelines[placed.row.episode].append(placed)
            for episode, name in timeline_names(episode_timelines).items():
                timeline_path = workspace / name
                write_timeline(timeline_path, episode_timelines[episode])
                archive.add(timeline_path, name)
            report_path = workspace / "processing_report.csv"
            write_report(report_path, sorted(records, key=lambda record: record["excel_row"]))
            archive.add(report_path, report_path.name)
            script_copy = workspace / SCRIPT_NAME
            shutil.copyfile(excel_path, script_copy)
            archive.add(script_copy, SCRIPT_NAME)
    return summarize(output_path, lines, names, progress)


def rewrite_line(line, rows, rewrite, generate, save, progress):
    """Pass 1.5 for one row: keep the rewrite closest to 1.0x, or flag the row for manual review."""
    row = line.row
    if word_count(row.text) <= SKIP_REWRITE_MAX_WORDS:
        line.skipped, line.note = True, SKIPPED_NOTE
        progress(f"Pass 1.5: Excel row {row.row_number} has {word_count(row.text)} word(s): {SKIPPED_NOTE}; kept at 1.0x")
        return
    context = tuple(other.text for other in rows
                    if other.group == row.group and other.row_number != row.row_number)
    attempts, best, notes = [], None, []
    for number in range(1, MAX_REWRITE_ATTEMPTS + 1):
        line.rewrite_calls = number
        try:
            text = rewrite(RewriteRequest(row.character, row.text, line.pass1.audio_duration_ms, line.slot_ms,
                                          context, tuple(attempts)))
        except (RewriteError, RuntimeError) as exc:
            notes.append(f"attempt {number}: {exc}")
            progress(f"Pass 1.5: Excel row {row.row_number} attempt {number} failed: {exc}")
            continue
        take, trimmed = generate(row, text)
        result = measure(take, line.slot_ms)
        attempts.append(Attempt(text, result.audio_duration_ms))
        progress(f"Pass 1.5: Excel row {row.row_number} attempt {number}: \"{text}\"; {describe(result)}")
        if best is None or abs(result.desired_speed - 1) < abs(best[3].desired_speed - 1):
            best = (text, take, trimmed, result)
        if result.is_normal:
            break
    if best is None:   # every Gemini call failed: keep the pass 1 take
        line.manual_review, line.note = True, "; ".join(notes)
        return
    line.text, take, line.trim_ms, line.pass1_5 = best
    line.rewritten = True
    save(KEPT_DIR, row, take)
    if line.pass1_5.needs_rewrite:
        line.manual_review = True
        notes.append(f"best rewrite still needs {format_sig(line.pass1_5.desired_speed)}x: kept at 1.0x")
        progress(f"Pass 1.5: Excel row {row.row_number} flagged for manual review")
    line.note = "; ".join(notes)


def describe(measurement):
    return (f"{measurement.audio_duration_ms} ms in a {measurement.tcr_duration_ms} ms slot, "
            f"needs {format_sig(measurement.desired_speed)}x (overrun {measurement.overrun_ms} ms, "
            f"{format_sig(measurement.percent_overrun)}%)")


def measurement_fields(prefix, measurement):
    return {f"{prefix}_audio_duration_ms": measurement.audio_duration_ms,
            f"{prefix}_overrun_ms": measurement.overrun_ms,
            f"{prefix}_percent_overrun": format_sig(measurement.percent_overrun),
            f"{prefix}_desired_speed": format_sig(measurement.desired_speed)}


def status(line):
    if line.skipped:
        return "SKIPPED_REWRITE"
    if line.manual_review:
        return "MANUAL_REVIEW"
    return "OK" if line.pass2.within_target else "TCR_OUT_OVERRUN"


def report_record(line, placed, track, fps):
    row = line.row
    return dict(
        excel_row=row.row_number, episode=row.episode, character=row.character, voice_id=row.voice_id,
        start_TCR=format_tcr(row.start_ms, fps), end_TCR=format_tcr(row.end_ms, fps), fps=fps,
        start_ms=row.start_ms, end_ms=row.end_ms, tcr_duration_ms=line.slot_ms,
        original_dialogue=row.text, final_dialogue=line.text,
        rewritten="yes" if line.rewritten else "no", rewrite_attempts=line.rewrite_calls,
        leading_trim_ms=line.trim_ms,
        **measurement_fields("pass1", line.pass1),
        **measurement_fields("pass1_5", line.pass1_5),
        pass2_speed=format_sig(line.pass2_speed),
        pass2_audio_duration_ms=line.pass2.audio_duration_ms, pass2_overrun_ms=line.pass2.overrun_ms,
        pass2_percent_overrun=format_sig(line.pass2.percent_overrun),
        within_target="yes" if line.pass2.within_target else "no",
        status=status(line), note=line.note, track=track,
        adjusted_start_TCR=format_tcr(placed.start_ms, fps), adjusted_end_TCR=format_tcr(placed.end_ms, fps))


def summarize(output_path, lines, names, progress):
    lines = list(lines.values())
    total = len(lines)
    rewritten = sum(line.rewritten for line in lines)
    manual = sum(line.manual_review for line in lines)
    skipped = sum(line.skipped for line in lines)
    fitted = sum(line.pass2_speed != 1.0 for line in lines)
    overrun = sum(status(line) == "TCR_OUT_OVERRUN" for line in lines)
    success_percent, success = success_rate(line.pass2 for line in lines)
    manual_percent = sig(manual / total * 100)
    progress(f"Complete: {len(names)} tracks; {rewritten} rows rewritten in pass 1.5; {fitted} rows sped up or "
             f"slowed down in pass 2; {manual} rows ({format_sig(manual_percent)}%) flagged for manual review; "
             f"{skipped} short rows not rewritten (SKIPPED_REWRITE)")
    mark = "✅" if success else "❌"   # Python 3.11 allows no backslashes inside f-string braces
    progress(f"Success: {format_sig(success_percent)}% of rows within target "
             f"(≤ +{NORMAL_TOLERANCE_PERCENT}% overrun; target {SUCCESS_TARGET_PERCENT}%) {mark}")
    if manual_percent > MANUAL_REVIEW_WARNING_PERCENT:
        progress(f"WARNING: more than {MANUAL_REVIEW_WARNING_PERCENT}% of rows need manual review. This should be "
                 "rare; check the script timings and the earlier passes before using this run.")
    return {"output": str(output_path), "rows": total, "tracks": len(names), "rewritten_rows": rewritten,
            "manual_review_rows": manual, "skipped_rows": skipped, "fitted_rows": fitted, "overrun_rows": overrun,
            "flagged_rows": manual + skipped + overrun, "success_percent": format_sig(success_percent), "success": success}
